"""Render the lifecycle table and complete state/event matrix; stdout is Markdown."""
import importlib.machinery
import importlib.util
from pathlib import Path


def load_script():
    loader = importlib.machinery.SourceFileLoader('devserve', str(Path(__file__).with_name('devserve')))
    spec = importlib.util.spec_from_loader(loader.name, loader)
    module = importlib.util.module_from_spec(spec)
    loader.exec_module(module)
    return module


def render():
    module = load_script()
    states = ('absent', 'starting', 'running', 'failed', 'stopped')
    events = ('up', 'ready', 'error', 'down', 'drop')
    lines = ['# Preview lifecycle', '',
             'Generated by `python3 scripts/render_lifecycle.py`; checked by the unit suite.', '',
             '```mermaid', 'stateDiagram-v2', '    [*] --> absent']
    for (state, event), (target, effects) in module.TRANSITIONS.items():
        lines.append(f'    {state} --> {target}: {event} / {", ".join(effects) or "none"}')
    lines += ['```', '', '| State | Event | Next | Effects |', '|---|---|---|---|']
    for state in states:
        for event in events:
            try:
                target, effects = module.step(state, event)
                lines.append(f'| {state} | {event} | {target} | {", ".join(effects) or "none"} |')
            except ValueError:
                lines.append(f'| {state} | {event} | invalid | none |')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    print(render(), end='')
